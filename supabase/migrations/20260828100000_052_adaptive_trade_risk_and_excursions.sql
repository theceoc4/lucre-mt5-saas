  drop constraint if exists trade_history_close_reason_check;
alter table public.trade_history
  add constraint trade_history_close_reason_check check (
    close_reason is null or close_reason = any (array[
      'tp','sl','manual','agent','eod_flat','basket_flatten',
      'ea_local_hard_stop','stop_out','rollover','other',
      'reconciled_missing_ea_report'
    ])
  );

comment on column public.strategies.risk_percent is
  'Maximum account-balance percentage at risk across all legs generated by one strategy signal.';
