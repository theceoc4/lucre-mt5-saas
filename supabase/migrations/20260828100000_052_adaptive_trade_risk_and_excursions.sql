alter table public.mt5_terminals
  add column if not exists ea_version text;

alter table public.strategies
  add column if not exists risk_percent numeric(6,3) not null default 0.500
    check (risk_percent > 0 and risk_percent <= 5);

update public.strategies
set risk_percent = 0.350
where kind = 'confirmed_trend_pullback' and risk_percent = 0.500;

